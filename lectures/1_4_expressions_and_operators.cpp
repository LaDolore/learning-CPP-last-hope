//1.4. Expressions and operatorsi
//
//	statement(инструкция) - 1) declaration
// 	                        2) expression(выражение)
//                          3) control statement(if, for, while...)
//                       
//	Примеры expression: x + 5;
//                      cout << x;
//                      и т.д.
//                    
//	Операторы: +, -, *, /, %, <<, >>, |, &, ^, &&, ||, <, >, <=, >=, !=.
//
//	Примеры использования & | ^ с бинарными числами:
//  a | b ставит 1, если 1 есть хотя бы в одном операнде (001 | 010 = 011)
//	a & b ставит 1, только если 1 есть в обоих операндах (011 & 010 = 010)
//	a ^ b ставит 1, если биты разные                     (011 ^ 010 = 001)
//
//	Оператор && вычисляется лениво, если левая часть ложна, правая даже не будет вычисляться (работает также с оператором ||)
//
//	Унарные операторы
//	Префиксные унарные операторы сразу возвращают результат своего действия, постфиксные возвращают изначальное значение, потом действуют на переменнуiю:
//	int a = 1;
//	int b = ++a; (b = 2)
//	int b = a++; (b = 1)
//	++a - lvalue
//	a++ - rvalue
//	Бинарные операции можно использлвать только на lvalue
//
//	В соответствии со стандартом, постфиксные операции более приоритетны чем префиксные,
//поэтому ++a++ = ++(a++) => так нельзя, так как a++ - rvalue
//
//	В тернарном операторе тоже работают ленивые вычисления, если аргумент истиный, правый не будет вычисляться и наоборот
//	Тернарный оператор считается lvalue только если две его ветки lvalue, в другом случае он rvalue, это определяется в compile-time
//	Обе ветки тернарного оператора должны возвращать один тип переменных, иначе CE, при этом он попытается привести их к общему типу
//
//  Если в одной строке несколько раз используется и изменяется одна и та же переменная, это скорее всего UB, но с С++ 17 возможно и не UB
//  Пример: i = ++1 + i++; - UB
// 
#include <iostream>

int main() {
	int x = 0;
	++x = x++;
}
